/**
 * The database. In production (Vercel) it is Neon Postgres, reached over HTTP so it suits
 * serverless functions; on a laptop with no DATABASE_URL it is one SQLite file (Node's built-in
 * driver). Queries are written once with `?` placeholders and plain SQL that both understand.
 */

export type Role = 'admin' | 'mill' | 'farmer';

export interface UserRow {
  id: number;
  email: string;
  name: string;
  role: Role;
  phone: string | null;
  password_hash: string;
  active: number;
  created_at: string;
}

type Param = string | number | null;

interface Driver {
  all<T>(sql: string, params: Param[]): Promise<T[]>;
  exec(sql: string): Promise<void>;
}

const TABLES = (pg: boolean) => {
  const id = pg ? 'id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'id INTEGER PRIMARY KEY AUTOINCREMENT';
  const real = pg ? 'DOUBLE PRECISION' : 'REAL';
  const now = pg ? `(to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD HH24:MI:SS'))` : `(datetime('now'))`;
  return [
    `CREATE TABLE IF NOT EXISTS users (
      ${id},
      email TEXT NOT NULL UNIQUE,
      name TEXT NOT NULL,
      role TEXT NOT NULL CHECK (role IN ('admin', 'mill', 'farmer')),
      phone TEXT,
      password_hash TEXT NOT NULL,
      active INTEGER NOT NULL DEFAULT 1,
      created_at TEXT NOT NULL DEFAULT ${now}
    )`,
    `CREATE TABLE IF NOT EXISTS sessions (
      token_hash TEXT PRIMARY KEY,
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at TEXT NOT NULL
    )`,
    `CREATE TABLE IF NOT EXISTS mills (
      user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      town TEXT NOT NULL,
      olives_t ${real} NOT NULL,
      margine_m3 ${real} NOT NULL,
      grignon_t ${real} NOT NULL,
      pond_m3 ${real} NOT NULL,
      trucks INTEGER NOT NULL,
      truck_m3 ${real} NOT NULL,
      season_days INTEGER NOT NULL,
      updated_at TEXT NOT NULL DEFAULT ${now}
    )`,
    `CREATE TABLE IF NOT EXISTS farms (
      user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
      name TEXT NOT NULL,
      town TEXT NOT NULL,
      area_ha ${real} NOT NULL,
      trees INTEGER NOT NULL,
      slope_pct ${real} NOT NULL,
      dist_well_m ${real} NOT NULL,
      dist_wadi_m ${real} NOT NULL,
      irrigated INTEGER NOT NULL,
      fertiliser_tnd ${real} NOT NULL,
      updated_at TEXT NOT NULL DEFAULT ${now}
    )`,
    `CREATE TABLE IF NOT EXISTS subscriptions (
      user_id INTEGER PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
      pack_id TEXT NOT NULL,
      status TEXT NOT NULL,
      started_at TEXT NOT NULL DEFAULT ${now}
    )`,
    `CREATE TABLE IF NOT EXISTS plans (
      ${id},
      user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      kind TEXT NOT NULL,
      input_json TEXT NOT NULL,
      output_json TEXT NOT NULL,
      cost_usd ${real} NOT NULL DEFAULT 0,
      created_at TEXT NOT NULL DEFAULT ${now}
    )`,
    `CREATE TABLE IF NOT EXISTS ai_spend (
      feature TEXT PRIMARY KEY,
      calls INTEGER NOT NULL DEFAULT 0,
      usd ${real} NOT NULL DEFAULT 0
    )`,
  ];
};

async function postgres(url: string): Promise<Driver> {
  const { neon } = await import('@neondatabase/serverless');
  const sql = neon(url);
  // `?` → `$1, $2…` (no query here contains a literal question mark).
  const numbered = (q: string) => {
    let n = 0;
    return q.replace(/\?/g, () => `$${++n}`);
  };
  return {
    all: async <T>(q: string, params: Param[]) => (await sql.query(numbered(q), params)) as T[],
    exec: async (q: string) => {
      await sql.query(q);
    },
  };
}

async function sqlite(): Promise<Driver> {
  const { DatabaseSync } = await import('node:sqlite');
  const { mkdirSync } = await import('node:fs');
  const { dirname, join } = await import('node:path');
  const file = process.env.DB_FILE ?? join(process.cwd(), 'data', 'sonae.db');
  mkdirSync(dirname(file), { recursive: true });
  const db = new DatabaseSync(file);
  db.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON;');
  return {
    all: async <T>(q: string, params: Param[]) => db.prepare(q).all(...params) as T[],
    exec: async (q: string) => {
      db.exec(q);
    },
  };
}

let ready: Promise<Driver> | null = null;

/** Connects once per process (or per warm serverless instance) and makes sure the tables exist. */
function driver(): Promise<Driver> {
  ready ??= (async () => {
    const url = process.env.DATABASE_URL;
    const pg = !!url;
    const d = pg ? await postgres(url) : await sqlite();
    for (const t of TABLES(pg)) await d.exec(t);
    return d;
  })().catch((e) => {
    ready = null;
    throw e;
  });
  return ready;
}

/** A UTC timestamp in the same text form as the column defaults. */
export const nowText = () => new Date().toISOString().slice(0, 19).replace('T', ' ');

export const db = {
  async all<T>(sql: string, ...params: Param[]): Promise<T[]> {
    return (await driver()).all<T>(sql, params);
  },
  async get<T>(sql: string, ...params: Param[]): Promise<T | undefined> {
    return (await this.all<T>(sql, ...params))[0];
  },
  async run(sql: string, ...params: Param[]): Promise<void> {
    await this.all(sql, ...params);
  },
};
